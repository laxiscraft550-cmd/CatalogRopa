/* ---------- Animaciones de scroll (reveal) ---------- */
function initReveal(root = document) {
  const els = root.querySelectorAll('.reveal:not(.reveal-on)');
  if (!('IntersectionObserver' in window)) {
    els.forEach((el) => el.classList.add('reveal-on'));
    return;
  }
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => {
      if (e.isIntersecting) {
        e.target.classList.add('reveal-on');
        io.unobserve(e.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });
  els.forEach((el) => io.observe(el));
}

/* ---------- Header que se contrae al hacer scroll ---------- */
function initHeaderScroll() {
  const header = document.querySelector('.site-header');
  if (!header) return;
  let last = 0;
  window.addEventListener('scroll', () => {
    const y = window.scrollY;
    header.classList.toggle('scrolled', y > 12);
    if (y > 200 && y > last) header.classList.add('hide-up');
    else header.classList.remove('hide-up');
    last = y;
  }, { passive: true });
}

/* ---------- Efecto ripple en botones ---------- */
function initRipple(root = document) {
  root.addEventListener('click', (e) => {
    const btn = e.target.closest('.btn, .chip, .size-opt');
    if (!btn) return;
    const r = document.createElement('span');
    r.className = 'ripple';
    const rect = btn.getBoundingClientRect();
    const d = Math.max(rect.width, rect.height);
    r.style.width = r.style.height = d + 'px';
    r.style.left = (e.clientX - rect.left - d / 2) + 'px';
    r.style.top = (e.clientY - rect.top - d / 2) + 'px';
    btn.appendChild(r);
    setTimeout(() => r.remove(), 650);
  });
}
